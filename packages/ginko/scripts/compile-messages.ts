// Compiles i18n/<code>.json into src/core/messages.compiled.ts, so core needs no ICU parser at runtime
// (sites import core; the parser would ship to every browser). Run after editing a catalog:
//   node packages/ginko/scripts/compile-messages.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { compileTree } from '@lupinum/ginko-i18n/compile'

const LOCALES = ['de', 'en', 'es', 'fr', 'it', 'ar']
const read = (locale: string) => JSON.parse(readFileSync(new URL(`../i18n/${locale}.json`, import.meta.url), 'utf8'))

export function compiledSource(): string {
  const trees = Object.fromEntries(LOCALES.map((locale) => [locale, compileTree(read(locale)).tree]))
  return `// Generated by scripts/compile-messages.ts from i18n/*.json. Do not edit.\nimport type { MessageTree } from '@lupinum/ginko-i18n/core'\n\nexport const compiled: Record<string, MessageTree> = ${JSON.stringify(trees, null, 1)}\n`
}

if (process.argv[1]?.endsWith('compile-messages.ts')) {
  writeFileSync(new URL('../src/core/messages.compiled.ts', import.meta.url), compiledSource())
}
