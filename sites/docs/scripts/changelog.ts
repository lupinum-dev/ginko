// Writes one changelog entry per release into content/changelog/, from the CHANGELOG.md files that Changesets
// keeps in the published packages. All packages release with one version, so an entry joins their notes.
//
//   node --experimental-strip-types scripts/changelog.ts          adds the releases that have no entry yet
//   node --experimental-strip-types scripts/changelog.ts --all    writes every generated entry again
//
// An entry that a person wrote (no "# generated" comment in its frontmatter) is never replaced.
// The build runs this, so a release that nobody added by hand is on the site after its deploy.
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..')
const out = join(root, 'sites/docs/content/changelog')
const PACKAGES = ['ginko', 'ginko-i18n', 'ginko-content', 'ginko-components', 'ginko-docs', 'ginko-preset-gastro', 'create-ginko']
const MARK = '# generated by scripts/changelog.ts from the CHANGELOG.md files of the packages'
const GROUPS = [['Add', 'Added'], ['Change', 'Changed'], ['Fix', 'Fixed'], ['Remove', 'Removed']] as const

interface Note { text: string; pr?: string; packages: string[] }

/** The notes of one package by version. A note is a top-level list item; "Updated dependencies" items are left out. */
function notesOf(name: string): Map<string, { text: string; pr?: string }[]> {
  const file = join(root, 'packages', name, 'CHANGELOG.md')
  const versions = new Map<string, { text: string; pr?: string }[]>()
  if (!existsSync(file)) return versions
  let version = ''
  let item: string[] | undefined
  const flush = () => {
    if (!item || !version) return
    const raw = item.join(' ').replace(/\s+/g, ' ').trim()
    item = undefined
    if (raw.startsWith('Updated dependencies')) return
    const pr = /^\[#(\d+)\]\(/.exec(raw)?.[1]
    // "[#12](…) [`abc`](…) Thanks [@name](…)! - The text" → "The text"
    const text = raw.replace(/^(?:\[#\d+\]\([^)]*\)\s*)?(?:\[`[0-9a-f]+`\]\([^)]*\)\s*)?(?:Thanks .*?!\s*)?-\s*/, '').trim()
    if (text) versions.get(version)!.push({ text, pr })
  }
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const heading = /^## (\d+\.\d+\.\d+\S*)/.exec(line)
    if (heading) { flush(); version = heading[1]!; versions.set(version, []); continue }
    if (line.startsWith('- ')) { flush(); item = [line.slice(2)]; continue }
    if (item && /^\s{2,}\S/.test(line) && !/^\s+- @lupinum\//.test(line)) { item.push(line.trim()); continue }
    if (line.startsWith('#')) flush()
  }
  flush()
  return versions
}

const releases = new Map<string, Note[]>()
for (const name of PACKAGES) {
  for (const [version, notes] of notesOf(name)) {
    const list = releases.get(version) ?? []
    releases.set(version, list)
    for (const note of notes) {
      const same = list.find((n) => n.text === note.text)
      if (same) same.packages.push(name)
      else list.push({ ...note, packages: [name] })
    }
  }
}

/** The day a version was tagged, else today: the build right after a release runs on its day. */
function dateOf(version: string): string {
  try {
    return execFileSync('git', ['log', '-1', '--format=%cs', `v${version}`], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
  } catch {
    return new Date().toISOString().slice(0, 10)
  }
}

function bodyOf(notes: Note[]): string {
  if (!notes.length) return 'A maintenance release. Nothing changes for a site.\n'
  const line = (n: Note) => `- ${n.text}${n.pr ? ` ([#${n.pr}](https://github.com/lupinum-dev/ginko/pull/${n.pr}))` : ''}`
  const used = new Set<Note>()
  const parts: string[] = []
  for (const [verb, title] of GROUPS) {
    const group = notes.filter((n) => n.text.startsWith(`${verb} `))
    if (!group.length) continue
    group.forEach((n) => used.add(n))
    parts.push(`### ${title}\n\n${group.map(line).join('\n')}`)
  }
  const rest = notes.filter((n) => !used.has(n))
  if (rest.length) parts.push(`### Other\n\n${rest.map(line).join('\n')}`)
  return `${parts.join('\n\n')}\n`
}

const all = process.argv.includes('--all')
let written = 0
for (const [version, notes] of releases) {
  const file = join(out, `v${version.replace(/\./g, '-')}.md`)
  if (existsSync(file)) {
    const generated = readFileSync(file, 'utf8').includes(MARK)
    if (!generated || !all) continue
  }
  writeFileSync(file, `---\n${MARK}\nversion: ${version}\ndate: ${dateOf(version)}\n---\n\n${bodyOf(notes)}`)
  written++
}
console.log(`changelog: ${written} entr${written === 1 ? 'y' : 'ies'} written, ${releases.size} releases known.`)
